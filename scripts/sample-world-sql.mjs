#!/usr/bin/env node
// Prints the whole Sample world (seed:demo's accounts, seed:library, seed:pulse) as SQL for a
// THROWAWAY Postgres, so supabase/tests/sample_world_check.sql can prove at the SQL level that
// field numbers do not move and that /i, /i/lamps and /m light up. No keys, no network: the same
// plan the seeds use, with stable stand in ids. Never point its output at the hosted project.
//   node scripts/sample-world-sql.mjs > /path/to/world.sql
import { randomUUID } from "node:crypto";
import { loadLibraryPlan, library, pulse, world } from "./sample-world.mjs";

const { sampleUuid, SAMPLE_INTERVIEW_TITLE } = world;
const now = new Date(process.argv[2] ?? Date.now());
const iso = now.toISOString();
const plan = loadLibraryPlan();

const out = [
  "-- Generated by scripts/sample-world-sql.mjs: the Sample world, for a throwaway database only.",
];
/** Insert rows through json_populate_recordset, so Postgres types every column itself. */
function insert(table, rows, { identity = false } = {}) {
  if (rows.length === 0) return;
  const cols = [...new Set(rows.flatMap((r) => Object.keys(r)))];
  const json = JSON.stringify(rows);
  if (json.includes("$sw$")) throw new Error("dollar quote clash");
  out.push(
    `insert into public.${table} (${cols.join(", ")})${identity ? " overriding system value" : ""}\n` +
      `select ${cols.join(", ")} from json_populate_recordset(null::public.${table}, $sw$${json}$sw$);`,
  );
}

// seed:demo: the four one tap accounts, all Sample.
const demo = ["teacher", "master", "reviewer", "officer"].map((role) => ({
  role,
  id: sampleUuid(`demo:${role}`),
}));
const masterProfile = (m) =>
  m.email === "master@demo.parampara.invalid"
    ? sampleUuid("demo:master")
    : sampleUuid(`profile:${m.key}`);
const masterId = (key) => sampleUuid(`master:${key}`);
const teacherId = (key) => sampleUuid(`teacher:${key}`);

const users = [
  ...demo.map((d) => d.id),
  ...plan.masters.filter((m) => m.email !== "master@demo.parampara.invalid").map(masterProfile),
  ...pulse.PULSE_TEACHERS.map((t) => teacherId(t.key)),
];
out.push(`insert into auth.users (id) values ${users.map((id) => `('${id}')`).join(", ")};`);

insert("profiles", [
  ...demo
    .filter((d) => d.role !== "master")
    .map((d) => ({
      id: d.id,
      role: d.role,
      display_name: `${d.role[0].toUpperCase()}${d.role.slice(1)} (Sample)`,
      district: "Koppal",
      is_sample: true,
      consented_at: iso,
      consent_version: `${d.role}@v1`,
    })),
  ...plan.masters.map((m) => ({
    id: masterProfile(m),
    role: "master",
    display_name: m.nameEn,
    district: m.district,
    is_sample: true,
    consented_at: iso,
    consent_version: "master@sample",
  })),
  ...pulse.PULSE_TEACHERS.map((t) => ({
    id: teacherId(t.key),
    role: "teacher",
    display_name: null,
    district: t.district,
    is_sample: true,
    consented_at: iso,
    consent_version: "teacher@sample",
  })),
]);
insert(
  "masters",
  plan.masters.map((m) => ({
    id: masterId(m.key),
    profile_id: masterProfile(m),
    years: m.years,
    school: m.school,
    classes: m.classes,
    show_name: "first",
    is_sample: true,
    consented_at: iso,
  })),
);

// seed:library: one synthetic interview per master, segments, and the cards that cite them.
let segmentId = 900000;
const interviews = [];
const segments = [];
const cards = [];
for (const m of plan.masters) {
  const mine = plan.cards.filter((c) => c.masterKey === m.key);
  if (mine.length === 0) continue;
  const interviewId = library.interviewIdFor(m.key);
  interviews.push({
    id: interviewId,
    master_id: masterId(m.key),
    status: "done",
    source: "import",
    title: SAMPLE_INTERVIEW_TITLE,
    is_sample: true,
  });
  const rows = library.buildSegments(interviewId, mine).map((r) => ({ ...r, id: ++segmentId }));
  segments.push(...rows.map(library.segmentInsertRow));
  const idOf = (card, kind) => rows.find((r) => r.card === card && r.kind === kind).id;
  for (const c of mine) {
    cards.push(
      library.cardRow(c, {
        masterId: masterId(m.key),
        interviewId,
        reviewerId: sampleUuid("demo:reviewer"),
        now: iso,
        segmentId: idOf,
      }),
    );
  }
}
insert("interviews", interviews);
insert("segments", segments, { identity: true });
insert("cards", cards);

// seed:pulse: the fortnight.
const pulseCards = Object.fromEntries(
  plan.cards
    .filter((c) => c.status === "approved")
    .map((c) => [
      c.libraryId,
      {
        id: c.dbId,
        master_id: masterId(c.masterKey),
        title_kn: c.title.kn,
        title_en: c.title.en,
        steps: c.steps,
        materials: c.materials,
        why_kn: c.why?.kn ?? null,
        why_en: c.why?.en ?? null,
      },
    ]),
);
const rows = pulse.buildPulseRows({
  now,
  teacherIds: Object.fromEntries(pulse.PULSE_TEACHERS.map((t) => [t.key, teacherId(t.key)])),
  cards: pulseCards,
  cardDistricts: library.cardDistricts(plan),
  uuid: randomUUID,
});
insert("questions", rows.questions);
insert("answers", rows.answers);
insert("tried", rows.tried);
insert("thanks", rows.thanks);
insert("human_queue", rows.queue);

console.log(out.join("\n"));
